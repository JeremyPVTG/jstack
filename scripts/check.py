#!/usr/bin/env python3
"""Validate owned skill metadata, local Markdown links, packs, and index freshness.

--sizes prints each skill's SKILL.md and references/ size in bytes, for the Skill-Size commit trailer.
"""
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    entries = {}
    for path in sorted((ROOT / 'skills').glob('*/SKILL.md')):
        text = path.read_text()
        match = re.match(r'---\nname: ([a-z0-9-]+)\ndescription: ([^\n]+)\n---\n', text)
        assert match, 'Invalid frontmatter: ' + str(path)
        name, description = match.groups()
        assert name == path.parent.name and len(description) <= 1024, name
        # Claude Code substitutes $0, $1, ... and $ARGUMENTS in a skill body with the invocation's arguments.
        assert not re.search(r'\$(\d|ARGUMENTS)', text), f'{name}: write amounts without $N (Claude Code treats $N as an argument)'
        assert name not in entries, 'Duplicate name: ' + name
        entries[name] = (description, path.relative_to(ROOT).as_posix())
    for pack, names in json.loads((ROOT / 'packs.json').read_text()).items():
        assert names and len(names) == len(set(names)), pack
        assert all(name in entries for name in names), pack
    index = '# Skills\n\nGenerated by `python3 scripts/check.py --write-index`. Read only the skill relevant to the request.\n\n'
    index += '\n'.join('- [' + name + '](' + path + '): ' + description for name, (description, path) in entries.items()) + '\n'
    if '--write-index' in sys.argv:
        (ROOT / 'INDEX.md').write_text(index)
    assert (ROOT / 'INDEX.md').read_text() == index, 'Run with --write-index'
    for path in ROOT.rglob('*.md'):
        if '.local' in path.parts or 'node_modules' in path.parts:
            continue
        for link in re.findall(r'\]\(([^)]+)\)', path.read_text()):
            if ':' in link or link.startswith('#'):
                continue
            assert (path.parent / link.split('#')[0]).exists(), str(path) + ': ' + link
    for path in ROOT.rglob('*.json'):
        if '.local' not in path.parts and 'node_modules' not in path.parts:
            json.loads(path.read_text())
    if '--sizes' in sys.argv:
        for name, (_, rel) in entries.items():
            folder = (ROOT / rel).parent
            refs = sum(f.stat().st_size for f in (folder / 'references').rglob('*') if f.is_file()) if (folder / 'references').exists() else 0
            print(f'{name:16} SKILL.md {(ROOT / rel).stat().st_size:6} bytes  references {refs:6} bytes')
    print('Validated', len(entries), 'skills, packs, Markdown links, JSON, and index.')


if __name__ == '__main__':
    main()
